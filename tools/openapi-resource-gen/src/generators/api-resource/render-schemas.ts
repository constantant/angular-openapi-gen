import type { EndpointModel } from './endpoint-model';
import { normalizeSchemaForValidation } from './parse-spec';

type Json = Record<string, unknown>;

function isObject(value: unknown): value is Json {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

/** Follows a local `#/components/<kind>/<name>` reference (a response or request body object). */
function resolveLocal(spec: Json, value: unknown): unknown {
  let current = value;
  for (let hops = 0; hops < 10 && isObject(current) && typeof current['$ref'] === 'string'; hops++) {
    const ref = current['$ref'] as string;
    if (!ref.startsWith('#/')) return undefined;
    current = ref
      .slice(2)
      .split('/')
      .map((part) => part.replace(/~1/g, '/').replace(/~0/g, '~'))
      .reduce<unknown>((node, key) => (isObject(node) ? node[key] : undefined), spec);
  }
  return current;
}

/** True when every `$ref` inside points into `#/components/schemas/`, which the file carries. */
function refsAreLocalSchemas(value: unknown): boolean {
  if (Array.isArray(value)) return value.every(refsAreLocalSchemas);
  if (!isObject(value)) return true;
  if (typeof value['$ref'] === 'string' && !value['$ref'].startsWith('#/components/schemas/')) return false;
  return Object.values(value).every(refsAreLocalSchemas);
}

function contentSchemas(spec: Json, content: unknown): Array<{ mediaType: string; schema: unknown }> {
  if (!isObject(content)) return [];
  return Object.entries(content)
    .filter(([, media]) => isObject(media) && media['schema'] !== undefined)
    .map(([mediaType, media]) => {
      const schema = (media as Json)['schema'];
      // A top-level ref to something the file does not carry (another component kind) is followed.
      const usable = refsAreLocalSchemas(schema) ? schema : resolveLocal(spec, schema);
      return { mediaType, schema: normalizeSchemaForValidation(usable) };
    })
    .filter(({ schema }) => schema !== undefined);
}

/**
 * The JSON Schemas of every endpoint's request body and documented responses, as one JSON document
 * for tools outside the app bundle (fixture checks, contract tests against a real backend).
 *
 * `components.schemas` is copied to the same place in the document, so the spec's own
 * `#/components/schemas/...` references stay valid (circular ones included). Validate a value with
 * the whole document as the root and a `$ref` to the schema you want, e.g.
 * `{ ...doc, $ref: '#/operations/GET_PET/responses/200/content/application~1json/schema' }`.
 * OpenAPI 3.0's `nullable: true` is rewritten to a `type` array, as JSON Schema has no `nullable`.
 */
export function renderSchemasDocument(rawSpec: Json, endpoints: EndpointModel[], specId: string): string {
  const components = isObject(rawSpec['components']) ? rawSpec['components'] : {};
  const operations: Json = {};
  for (const ep of endpoints) {
    const pathItem = isObject(rawSpec['paths']) ? (rawSpec['paths'] as Json)[ep.apiPath] : undefined;
    const op = isObject(pathItem) ? pathItem[ep.method] : undefined;
    if (!isObject(op)) continue;

    const entry: Json = { method: ep.method, path: ep.apiPath };
    const body = resolveLocal(rawSpec, op['requestBody']);
    if (isObject(body)) {
      const content = Object.fromEntries(contentSchemas(rawSpec, body['content']).map(({ mediaType, schema }) => [mediaType, { schema }]));
      entry['requestBody'] = { required: body['required'] === true, content };
    }
    const responses: Json = {};
    for (const [status, raw] of Object.entries(isObject(op['responses']) ? op['responses'] : {})) {
      const response = resolveLocal(rawSpec, raw);
      const content = isObject(response)
        ? Object.fromEntries(contentSchemas(rawSpec, response['content']).map(({ mediaType, schema }) => [mediaType, { schema }]))
        : {};
      responses[status] = { content };
    }
    entry['responses'] = responses;
    operations[ep.tokenName] = entry;
  }

  const document = {
    $comment: 'Generated by openapi-resource-gen --emitSchemas. Validate with this document as the root schema.',
    specId,
    components: { schemas: normalizeSchemaForValidation(components['schemas'] ?? {}) },
    operations,
  };
  return JSON.stringify(document, null, 2) + '\n';
}
